class ProductResponse {
  ProductResponse({
    required this.productAllItems,
    required this.productPage,
    required this.productCountItems,
    required this.banner,
    required this.category,
    required this.products,
  });
  late final int productAllItems;
  late final int productPage;
  late final int productCountItems;
  late final List<Banner> banner;
  late final List<String> category;
  late final List<Products> products;

  ProductResponse.fromJson(Map<String, dynamic> json){
    productAllItems = json['productAllItems'];
    productPage = json['productPage'];
    productCountItems = json['productCountItems'];
    banner = List.from(json['banner']).map((e)=>Banner.fromJson(e)).toList();
    category = List.castFrom<dynamic, String>(json['category']);
    products = List.from(json['products']).map((e)=>Products.fromJson(e)).toList();
  }
}

class Banner {
  Banner({
    required this.image,
    required this.route,
    required this.url,
  });
  late final String image;
  late final String route;
  late final String url;

  Banner.fromJson(Map<String, dynamic> json){
    image = json['image'];
    route = json['route'];
    url = json['url'];
  }

  Map<String, dynamic> toJson() {
    final data = <String, dynamic>{};
    data['image'] = image;
    data['route'] = route;
    data['url'] = url;
    return data;
  }
}

